-- Sensor tables for the single metered "Rental House".
--
-- The original set assumed live_sensor_readings already existed (it altered it
-- but never created it), so every table is created here with IF NOT EXISTS and
-- then topped up with ADD COLUMN IF NOT EXISTS. That works on a fresh project
-- and on one where some of these tables were already created by hand.
--
-- The sensor name stored in the database is always 'Rental House'.
-- (pzem_status, which holds relay on/off state, is handled in a later file.)


-- ---------------------------------------------------------------------------
-- live_sensor_readings: latest reading per device + sensor
-- ---------------------------------------------------------------------------

create table if not exists public.live_sensor_readings (
  id bigint generated by default as identity primary key,
  device_id text not null,
  sensor text not null,
  voltage numeric,
  current numeric,
  voltage_v numeric,
  current_a numeric,
  power_w numeric,
  energy_kwh numeric,
  recorded_at timestamptz,
  updated_at timestamptz not null default now()
);

alter table public.live_sensor_readings
  add column if not exists voltage numeric,
  add column if not exists current numeric,
  add column if not exists voltage_v numeric,
  add column if not exists current_a numeric,
  add column if not exists power_w numeric,
  add column if not exists energy_kwh numeric,
  add column if not exists recorded_at timestamptz,
  add column if not exists updated_at timestamptz not null default now();

create unique index if not exists live_sensor_readings_device_sensor_uidx
  on public.live_sensor_readings (device_id, sensor);

-- If the table pre-existed with a CHECK that lists the old room names, remove it.
do $$
declare
  c record;
begin
  for c in
    select conname
      from pg_constraint
     where conrelid = 'public.live_sensor_readings'::regclass
       and contype = 'c'
       and pg_get_constraintdef(oid) ilike '%Sala%'
  loop
    execute format('alter table public.live_sensor_readings drop constraint %I', c.conname);
  end loop;
end $$;

alter table public.live_sensor_readings
  drop constraint if exists live_sensor_readings_sensor_name;
-- NOT VALID: new writes must use 'Rental House'; any old rows are left alone.
alter table public.live_sensor_readings
  add constraint live_sensor_readings_sensor_name
  check (sensor = 'Rental House') not valid;


-- ---------------------------------------------------------------------------
-- energy_readings_raw: every reading received, kept for history
-- ---------------------------------------------------------------------------

create table if not exists public.energy_readings_raw (
  id bigint generated by default as identity primary key,
  device_id text not null,
  sensor text not null,
  voltage numeric,
  current numeric,
  voltage_v numeric,
  current_a numeric,
  power_w numeric,
  energy_kwh numeric,
  recorded_at timestamptz not null,
  received_at timestamptz not null default now()
);

alter table public.energy_readings_raw
  add column if not exists voltage numeric,
  add column if not exists current numeric,
  add column if not exists voltage_v numeric,
  add column if not exists current_a numeric,
  add column if not exists power_w numeric,
  add column if not exists energy_kwh numeric,
  add column if not exists recorded_at timestamptz,
  add column if not exists received_at timestamptz not null default now();

-- Required by the ingestion RPC's ON CONFLICT (device_id, sensor, recorded_at).
create unique index if not exists energy_readings_raw_unique_reading_uidx
  on public.energy_readings_raw (device_id, sensor, recorded_at);

create index if not exists energy_readings_raw_device_idx on public.energy_readings_raw (device_id);
create index if not exists energy_readings_raw_sensor_idx on public.energy_readings_raw (sensor);
create index if not exists energy_readings_raw_recorded_at_idx on public.energy_readings_raw (recorded_at);

alter table public.energy_readings_raw
  drop constraint if exists energy_readings_raw_sensor_name;
alter table public.energy_readings_raw
  add constraint energy_readings_raw_sensor_name
  check (sensor = 'Rental House') not valid;


-- ---------------------------------------------------------------------------
-- current_kwh_readings: kWh used per day (drives the monthly target alert)
-- ---------------------------------------------------------------------------

create table if not exists public.current_kwh_readings (
  id bigint generated by default as identity primary key,
  reading_date date not null,
  rental_kwh numeric not null default 0,
  total_kwh numeric not null default 0, -- kept equal to rental_kwh
  updated_at timestamptz not null default now()
);

alter table public.current_kwh_readings
  add column if not exists rental_kwh numeric not null default 0;

create unique index if not exists current_kwh_readings_reading_date_uidx
  on public.current_kwh_readings (reading_date);


-- ---------------------------------------------------------------------------
-- Row level security: signed-in users can read; only the service role writes
-- ---------------------------------------------------------------------------

alter table public.live_sensor_readings enable row level security;
alter table public.current_kwh_readings enable row level security;
alter table public.energy_readings_raw enable row level security;

drop policy if exists live_sensor_readings_select_authenticated on public.live_sensor_readings;
create policy live_sensor_readings_select_authenticated on public.live_sensor_readings
  for select to authenticated using (true);

drop policy if exists current_kwh_readings_select_authenticated on public.current_kwh_readings;
create policy current_kwh_readings_select_authenticated on public.current_kwh_readings
  for select to authenticated using (true);

drop policy if exists energy_readings_raw_select_authenticated on public.energy_readings_raw;
create policy energy_readings_raw_select_authenticated on public.energy_readings_raw
  for select to authenticated using (true);


-- ---------------------------------------------------------------------------
-- Realtime
-- ---------------------------------------------------------------------------

do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'live_sensor_readings') then
    alter publication supabase_realtime add table public.live_sensor_readings;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'current_kwh_readings') then
    alter publication supabase_realtime add table public.current_kwh_readings;
  end if;
end;
$$;
