-- Persist monthly target decisions and refresh them whenever daily energy data
-- changes. This keeps threshold detection independent of the web application.

create table if not exists public.energy_target_status (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  room_id text not null,
  month_start date not null,
  target_kwh numeric(12, 3) not null default 0,
  consumed_kwh numeric(12, 3) not null default 0,
  status text not null default 'within_target',
  decision text not null default 'pending',
  reached_at timestamptz,
  notified_at timestamptz,
  decided_at timestamptz,
  paused_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint energy_target_status_room_check
    check (room_id in ('sala', 'living-room', 'master-bedroom')),
  constraint energy_target_status_status_check
    check (status in ('within_target', 'target_reached', 'paused')),
  constraint energy_target_status_decision_check
    check (decision in ('pending', 'continue', 'pause')),
  constraint energy_target_status_values_check
    check (target_kwh >= 0 and consumed_kwh >= 0),
  constraint energy_target_status_unique
    unique (user_id, room_id, month_start)
);

alter table public.energy_target_status enable row level security;

drop policy if exists energy_target_status_select_own on public.energy_target_status;
create policy energy_target_status_select_own
  on public.energy_target_status for select to authenticated
  using (user_id = auth.uid());

drop policy if exists energy_target_status_update_own on public.energy_target_status;
create policy energy_target_status_update_own
  on public.energy_target_status for update to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

drop policy if exists energy_target_status_insert_own on public.energy_target_status;
create policy energy_target_status_insert_own
  on public.energy_target_status for insert to authenticated
  with check (user_id = auth.uid());

create or replace function public.refresh_energy_target_status(p_month_start date default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_month_start date := coalesce(
    p_month_start,
    date_trunc('month', timezone('Asia/Manila', now()))::date
  );
  v_next_month date := (v_month_start + interval '1 month')::date;
  v_sala numeric := 0;
  v_living numeric := 0;
  v_master numeric := 0;
  v_config record;
begin
  select
    coalesce(sum(sala_kwh), 0),
    coalesce(sum(living_kwh), 0),
    coalesce(sum(master_kwh), 0)
  into v_sala, v_living, v_master
  from public.current_kwh_readings
  where reading_date >= v_month_start
    and reading_date < v_next_month;

  for v_config in
    select user_id, sala_kwh, living_room_kwh, master_bedroom_kwh
    from public.setup_energy
  loop
    insert into public.energy_target_status (
      user_id, room_id, month_start, target_kwh, consumed_kwh,
      status, decision, reached_at, notified_at, updated_at
    ) values
      (v_config.user_id, 'sala', v_month_start, v_config.sala_kwh, v_sala,
       case when v_config.sala_kwh > 0 and v_sala >= v_config.sala_kwh then 'target_reached' else 'within_target' end,
       'pending', case when v_config.sala_kwh > 0 and v_sala >= v_config.sala_kwh then now() end,
       case when v_config.sala_kwh > 0 and v_sala >= v_config.sala_kwh then now() end, now()),
      (v_config.user_id, 'living-room', v_month_start, v_config.living_room_kwh, v_living,
       case when v_config.living_room_kwh > 0 and v_living >= v_config.living_room_kwh then 'target_reached' else 'within_target' end,
       'pending', case when v_config.living_room_kwh > 0 and v_living >= v_config.living_room_kwh then now() end,
       case when v_config.living_room_kwh > 0 and v_living >= v_config.living_room_kwh then now() end, now()),
      (v_config.user_id, 'master-bedroom', v_month_start, v_config.master_bedroom_kwh, v_master,
       case when v_config.master_bedroom_kwh > 0 and v_master >= v_config.master_bedroom_kwh then 'target_reached' else 'within_target' end,
       'pending', case when v_config.master_bedroom_kwh > 0 and v_master >= v_config.master_bedroom_kwh then now() end,
       case when v_config.master_bedroom_kwh > 0 and v_master >= v_config.master_bedroom_kwh then now() end, now())
    on conflict (user_id, room_id, month_start) do update set
      target_kwh = excluded.target_kwh,
      consumed_kwh = excluded.consumed_kwh,
      status = case
        when energy_target_status.target_kwh <> excluded.target_kwh then excluded.status
        when energy_target_status.decision = 'pause' then 'paused'
        when energy_target_status.decision = 'continue'
          and excluded.status = 'target_reached' then 'target_reached'
        else excluded.status
      end,
      decision = case
        when energy_target_status.target_kwh <> excluded.target_kwh then 'pending'
        else energy_target_status.decision
      end,
      reached_at = case
        when energy_target_status.target_kwh <> excluded.target_kwh
          and excluded.status = 'target_reached' then now()
        when energy_target_status.reached_at is not null then energy_target_status.reached_at
        when excluded.status = 'target_reached' then now()
      end,
      notified_at = case
        when energy_target_status.target_kwh <> excluded.target_kwh
          and excluded.status = 'target_reached' then now()
        when energy_target_status.notified_at is not null then energy_target_status.notified_at
        when excluded.status = 'target_reached' then now()
      end,
      decided_at = case
        when energy_target_status.target_kwh <> excluded.target_kwh then null
        else energy_target_status.decided_at
      end,
      paused_at = case
        when energy_target_status.target_kwh <> excluded.target_kwh then null
        else energy_target_status.paused_at
      end,
      updated_at = now();
  end loop;
end;
$$;

create or replace function public.refresh_energy_target_status_after_daily_reading()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.refresh_energy_target_status();
  return null;
end;
$$;

drop trigger if exists current_kwh_readings_refresh_target_status
  on public.current_kwh_readings;
create trigger current_kwh_readings_refresh_target_status
  after insert or update on public.current_kwh_readings
  for each statement execute function public.refresh_energy_target_status_after_daily_reading();

drop trigger if exists setup_energy_refresh_target_status
  on public.setup_energy;
create trigger setup_energy_refresh_target_status
  after insert or update on public.setup_energy
  for each statement execute function public.refresh_energy_target_status_after_daily_reading();

grant execute on function public.refresh_energy_target_status(date) to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and tablename = 'energy_target_status'
  ) then
    alter publication supabase_realtime add table public.energy_target_status;
  end if;
end;
$$;
