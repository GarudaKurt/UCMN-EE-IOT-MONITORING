-- Latest room/house readings pushed by Node-RED, one JSON object per row:
--   { "room": "Rental House", "kWh": 1.25, "timestamp": "2026-09-29T14:30:00+08:00" }
--
-- This replaces the two earlier migrations (add_current_readings and
-- move_current_readings_to_table). The first added a JSONB column to
-- nodered_sensors and the second moved it out again; since neither was applied,
-- the table is created directly and nodered_sensors is not touched.

create table if not exists public.current_readings (
  id bigint generated by default as identity primary key,
  reading jsonb not null,
  created_at timestamptz not null default now(),
  constraint current_readings_reading_is_object
    check (jsonb_typeof(reading) = 'object'),
  constraint current_readings_reading_has_required_fields
    check (
      reading ? 'room'
      and reading ? 'kWh'
      and reading ? 'timestamp'
    )
);

-- The original had no row level security, which leaves a public-schema table
-- open to anyone holding the anon key. Node-RED writes with the service role,
-- which bypasses RLS, so only read access is needed for the app.
alter table public.current_readings enable row level security;

drop policy if exists current_readings_select_authenticated on public.current_readings;
create policy current_readings_select_authenticated
  on public.current_readings
  for select
  to authenticated
  using (true);
