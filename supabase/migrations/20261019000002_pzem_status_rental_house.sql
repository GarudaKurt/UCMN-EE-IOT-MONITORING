-- Relay on/off state for the rental house (the app's toggle switch).
-- pzem_status was referenced by the old files but never created in them, so it
-- is created here if it does not exist yet. Live readings live in
-- live_sensor_readings; this table only stores relay state.
--
-- The app expects exactly one row with group_id = 'rental-house'.

create table if not exists public.pzem_status (
  id bigint generated by default as identity primary key,
  group_id text not null,
  is_on boolean not null default true,
  updated_at timestamptz not null default now()
);

create unique index if not exists pzem_status_group_id_uidx
  on public.pzem_status (group_id);

drop trigger if exists pzem_status_set_updated_at on public.pzem_status;
create trigger pzem_status_set_updated_at
  before update on public.pzem_status
  for each row execute function public.set_updated_at();

alter table public.pzem_status enable row level security;

-- Any signed-in user can read and flip the relay. Fine for a single household;
-- tighten this (for example, by adding an owner column) if several people use
-- the same project.
drop policy if exists pzem_status_select_authenticated on public.pzem_status;
create policy pzem_status_select_authenticated on public.pzem_status
  for select to authenticated using (true);

drop policy if exists pzem_status_update_authenticated on public.pzem_status;
create policy pzem_status_update_authenticated on public.pzem_status
  for update to authenticated using (true) with check (true);

-- Seed the single row. If an existing pzem_status table has extra NOT NULL
-- columns, this is skipped with a notice and the row must be added by hand.
do $$
begin
  insert into public.pzem_status (group_id, is_on)
  values ('rental-house', true)
  on conflict (group_id) do nothing;
exception when others then
  raise notice 'Could not seed pzem_status: %', sqlerrm;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'pzem_status'
  ) then
    alter publication supabase_realtime add table public.pzem_status;
  end if;
end;
$$;
